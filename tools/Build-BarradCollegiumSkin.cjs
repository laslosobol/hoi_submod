"use strict";
// Rasterize code-native controls; AI-painted department backgrounds are converted separately.
const fs = require("node:fs"), path = require("node:path"), sharp = require("sharp"), lucide = require("lucide");
const root = path.resolve(__dirname, ".."), out = path.join(root,"mod/HoISubmod/gfx/interface/HSM_BAR/mtk");
const src = path.join(root,"art/source/HSM_BAR_mtk_controls");
const themes = {viira: ["#334d5a","#8cbec9",lucide.Sparkles], leopold: ["#494b46","#c0ae76",lucide.Wrench], silver: ["#58333e","#c39b9e",lucide.HeartPulse], asinti: ["#294c3e","#a5be9d",lucide.Orbit]};
fs.mkdirSync(out,{recursive:true}); fs.mkdirSync(src,{recursive:true});
let gfx = "# Generated by tools/Build-BarradCollegiumSkin.cjs. All buttons use native shader states.\nspriteTypes = {\n";
function register(name, file, shader = "buttonstate") { gfx += ` spriteType = { name = "GFX_HSM_BAR_mtk_${name}" texturefile = "gfx/interface/HSM_BAR/mtk/${file}.tga" noOfFrames = 1 effectFile = "gfx/FX/${shader}.lua" legacy_lazy_load = no }\n`; }
async function control(name, w, h, fill, accent, selected, glyph = null, paper = false) {
    const paths = glyph ? glyph.map(([tag, attrs])=>`<${tag} ${Object.entries(attrs).map(([k,v])=>`${k}="${v}"`).join(" ")}/>`).join("") : "";
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
<defs><linearGradient id="rim" x2="0" y2="1"><stop stop-color="${paper ? '#c9cec3' : '#8a948c'}"/><stop offset="1" stop-color="${paper ? '#999f94' : '#27362d'}"/></linearGradient></defs>
<rect x="1" y="2" width="${w-2}" height="${h-3}" rx="3" fill="url(#rim)" stroke="${paper ? '#a7ada2' : '#18221c'}"/>
<rect x="2.5" y="3.5" width="${w-5}" height="${h-6}" rx="2" fill="${paper ? (selected ? '#f4f2e5' : '#dce1d5') : (selected ? fill : '#293630')}"/>
<path d="M5 4h${w-10}" stroke="${paper ? '#fff' : '#c8cbb9'}" stroke-opacity=".25"/>
${selected ? `<path d="M8 ${h-5}h${w-16}" stroke="${accent}" stroke-width="2"/>` : ''}
${glyph ? `<g transform="translate(${w < 40 ? '6 6' : '12 8'}) scale(.8)" fill="none" stroke="#eeeedd" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${paths}</g>` : ''}
</svg>\n`;
    const rgba=await sharp(Buffer.from(svg),{density:288}).resize(w,h).ensureAlpha().raw().toBuffer(), bytes=Buffer.alloc(18+w*h*4);
    bytes[2]=2; bytes.writeUInt16LE(w,12); bytes.writeUInt16LE(h,14); bytes[16]=32; bytes[17]=8;
    for(let y=0;y<h;y++) for(let x=0;x<w;x++){const s=(y*w+x)*4,d=18+((h-1-y)*w+x)*4; bytes[d]=rgba[s+2];bytes[d+1]=rgba[s+1];bytes[d+2]=rgba[s];bytes[d+3]=rgba[s+3];}
    fs.writeFileSync(path.join(src,name+".svg"),svg);fs.writeFileSync(path.join(out,name+".tga"),bytes);register(name,name);
}
async function main(){
    for(const [d,[fill,accent,icon]] of Object.entries(themes)){
        register(d,d,"static_button");
        for(const selected of [false,true]){
            const s=selected?"_selected":"";
            await control("dept_"+d+s,228,36,fill,accent,selected,icon);
            await control("project_"+d+s,228,36,fill,accent,selected);
            await control("experiment_"+d+s,294,40,fill,accent,selected);
        }
    }
    for(const selected of [false,true]) await control("doc"+(selected?"_selected":""),144,34,"#dce1d5","#864a48",selected,null,true);
    await control("action",294,36,"#33433a","#b5c5aa",false);
    await control("ledger",32,32,"#33433a","#b5c5aa",false,lucide.Calculator);
    const license=path.join(path.dirname(require.resolve("lucide/package.json")),"LICENSE");
    fs.copyFileSync(license,path.join(src,"Lucide-LICENSE.txt"));fs.copyFileSync(license,path.join(out,"Lucide-LICENSE.txt"));
    fs.writeFileSync(path.join(root,"mod/HoISubmod/interface/HSM_BAR_mtk.gfx"),gfx+"}\n");
    console.log("Collegium skin: four department backgrounds and 28 antialiased control sprites.");
}
main().catch(error=>{console.error(error);process.exitCode=1;});
