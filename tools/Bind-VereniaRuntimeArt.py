"""Hash-checked, artwork-only MIO/advisor reconciliation. No native definitions edited.

--check is read-only; --apply writes only three dedicated generated script files.
Advisor approval is deliberately separate from preparing briefs.
"""
import argparse
import hashlib
import json
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
API = runpy.run_path(str(ROOT / 'tools/Bind-VereniaIcons.py'))
require, Files = API['require'], API['Files']
ART = 'art/verenia/'
MOD = 'mod/HoISubmod/'
NATIVE = 'EaW/history/general/generic_advisors.txt'
MIO_NATIVE = 'EaW/common/military_industrial_organization/organizations/00_generic_organization.txt'
GFX = MOD + 'interface/HSM_VER_runtime_art.gfx'
EFFECT = MOD + 'common/scripted_effects/HSM_VER_runtime_art.txt'
HOOK = MOD + 'common/on_actions/HSM_VER_runtime_art.txt'
HEADER = '# Generated by Bind-VereniaRuntimeArt.py; artwork only.\n'
SCOPE = 'OR = { original_tag = ERI original_tag = EYR original_tag = AVI }'
MAPPING = {
    'tank': 'tank', 'escort_ship': 'naval', 'light_aircraft': 'light_aircraft',
    'medium_aircraft': 'medium_aircraft', 'heavy_aircraft': 'heavy_aircraft',
    'naval_aircraft': 'naval_aircraft', 'artillery': 'artillery',
    'motorized_mechanized': 'motorized_equipment', 'general_aircraft': None,
    'infantry_equipment': 'infantry_equipment',
}

def sha(raw):
    return hashlib.sha256(raw).hexdigest()

def read(files, name):
    return API['read_json'](files, name)

def selectors(raw):
    result = {}
    for _, node in API['walk'](API['spans'](raw.decode('utf-8-sig'))):
        if node.key != 'generate_character':
            continue
        fields = {n.key: n for n in node.children}
        token = fields['token_base'].value
        advisor = {n.key: n for n in fields['advisor'].children}
        traits = [n.key for n in advisor['traits'].children]
        require(len(traits) == 1, 'Expected single native advisor trait')
        result[token] = dict(flag='is_generic', slot=advisor['slot'].value,
                             trait=traits[0], gender=fields['gender'].value if 'gender' in fields else None)
    require(len(result) == 30, 'Expected 30 native templates')
    require(len({json.dumps(s, sort_keys=True) for s in result.values()}) == 30,
            'Ambiguous advisor selectors')
    return result

def asset(files, row, size):
    require(row.get('approved') is True and bool(row.get('review')), 'Missing approval/review')
    source = row['source']
    API['relative'](source, ART)
    raw = files.read(source)
    require(raw is not None and sha(raw) == row.get('source_sha256'), 'Source hash mismatch: ' + source)
    require(len(row['exports']) == 1, 'Expected single export')
    export = row['exports'][0]
    API['relative'](export['path'], MOD + 'gfx/')
    require((export['width'], export['height']) == size, 'Export dimensions mismatch')
    raw = files.read(export['path'])
    require(raw is not None and sha(raw) == export.get('sha256'), 'Export hash mismatch')
    API['native_tga'](raw, size)

def plan(files):
    advisors = read(files, ART + 'generated-advisor-bindings.json')
    mios = read(files, ART + 'mio-bindings.json')
    for data, native in ((advisors, NATIVE), (mios, MIO_NATIVE)):
        require(data.get('schema_version') == 1, 'Unsupported manifest schema')
        require(data['source_file'] == native and sha(files.read(native)) == data['source_file_sha256'],
                'Native pin drift: ' + native)
        override = files.read(MOD + native.removeprefix('EaW/'))
        require(override is None or override == files.read(native), 'Native override requires re-audit: ' + native)
        require(data['countries'] == ['ERI', 'EYR', 'AVI'], 'Country scope drift')
    expected = selectors(files.read(NATIVE))
    require(len(advisors['records']) == 30 and {r['id'] for r in advisors['records']} == set(expected),
            'Advisor inventory mismatch')
    require(len(mios['records']) == 10 and {r['id'] for r in mios['records']} ==
            {'generic_' + k + '_organization' for k in MAPPING}, 'MIO inventory mismatch')
    companies = {r['id']: r for r in read(files, ART + 'company-bindings.json')['records']}
    mio_export = read(files, ART + 'mio-exports.json')
    baseline = read(files, ART + 'mio-exports-hashes.json')
    native_ids = {n.key for n in API['spans'](files.read(MIO_NATIVE).decode('utf-8-sig'))}
    sprites, mio_lines, advisor_lines, completed = [], [], [], []
    for row in mios['records']:
        key = row['id'].removeprefix('generic_').removesuffix('_organization')
        require(row['id'] in native_ids, 'Unknown native MIO')
        if not row.get('approved'):
            continue
        company = MAPPING[key]
        if company:
            ref = companies['generic_' + company + '_manufacturer']
            sprite = 'GFX_idea_HSM_VER_COMP_' + ref['id']
            require(row['company_id'] == ref['id'] and row['sprite'] == sprite, 'Wrong company mapping')
            require(all(row[k] == ref[k] for k in ('source', 'source_sha256', 'exports')), 'Company evidence drift')
            asset(files, ref, (64, 64))
        else:
            require(len(mio_export) == 1, 'Expected one general aircraft export')
            ref = mio_export[0]
            require(ref.get('approved') is True and ref.get('review') and ref['target'] == row['id'], 'MIO export approval mismatch')
            require(row['source'] == ref['source'] and row['source_sha256'] == baseline[row['source']], 'MIO source drift')
            require([{k: e[k] for k in ('path','width','height')} for e in row['exports']] == ref['exports'], 'MIO export drift')
            require(row['exports'][0]['sha256'] == baseline[row['exports'][0]['path']], 'MIO baseline drift')
            sprite = 'GFX_idea_HSM_VER_MIO_general_aircraft'
            require(row['sprite'] == sprite, 'MIO sprite drift')
            sprites.append((sprite, row['exports'][0]['path']))
        asset(files, row, (64, 64))
        mio_lines.append('if = { limit = { is_military_industrial_organization = ' + row['id'] + ' } set_mio_icon = ' + sprite + ' }')
        completed.append(('mio', row))
    for row in advisors['records']:
        token = row['id']
        require(row['selector'] == expected[token], 'Advisor selector drift: ' + token)
        require(row['source'] == ART + 'HSM_VER_GEN_' + token + '.png', 'Advisor source path drift')
        require(len(row['exports']) == 1 and row['exports'][0]['path'] == MOD + 'gfx/portraits/HSM_VER/generated/' + token + '.tga', 'Advisor export path drift')
        if not row.get('approved'):
            continue
        asset(files, row, (65, 67))
        s = row['selector']
        gender = '' if s['gender'] is None else ' is_female = ' + ('yes' if s['gender'] == 'female' else 'no')
        sprite = 'GFX_HSM_VER_GEN_' + token
        sprites.append((sprite, row['exports'][0]['path']))
        advisor_lines.append('if = { limit = { has_character_flag = is_generic has_advisor_role = ' + s['slot'] + ' has_trait = ' + s['trait'] + gender + ' } set_portraits = { army = { small = ' + sprite + ' } } }')
        completed.append(('generated_advisor', row))
    # Reused sprites must resolve uniquely to the reviewed company export.
    all_sprites = {}
    for name in (files.interfaces if hasattr(files, 'interfaces') else files.glob(MOD + 'interface', '**/*.gfx')):
        if name == GFX:
            continue
        for _, node in API['walk'](API['spans'](files.read(name).decode('utf-8-sig'))):
            if node.key.lower() == 'spritetype':
                fields = {n.key.lower(): n.value for n in node.children}
                all_sprites.setdefault(fields.get('name'), []).append(fields.get('texturefile'))
    for kind, row in completed:
        if kind == 'mio' and row.get('company_id'):
            require(all_sprites.get(row['sprite']) == [row['exports'][0]['path'].removeprefix(MOD)], 'Reused sprite missing/collision')
    for sprite, _ in sprites:
        require(sprite not in all_sprites, 'Sprite collision: ' + sprite)
    effect = HEADER + 'HSM_VER_reconcile_runtime_art = {\n if = { limit = { ' + SCOPE + ' }\n'
    if mio_lines:
        effect += ' every_military_industrial_organization = { include_invisible = yes\n' + '\n'.join(mio_lines) + '\n }\n'
    if advisor_lines:
        effect += ' every_character = {\n' + '\n'.join(advisor_lines) + '\n }\n'
    effect += ' }\n}\n'
    hook = HEADER + 'on_actions = {\n on_startup = { effect = { every_country = { HSM_VER_reconcile_runtime_art = yes } } }\n # Country scope; catches existing saves and later-created countries within one week.\n on_weekly = { effect = { HSM_VER_reconcile_runtime_art = yes } }\n}\n'
    gfx = HEADER + 'spriteTypes = {\n' + '\n'.join(' spriteType = { name = ' + s + ' textureFile = "' + p.removeprefix(MOD) + '" }' for s,p in sprites) + '\n}\n'
    outputs = {GFX: gfx.encode(), EFFECT: effect.encode(), HOOK: hook.encode()}
    for name, raw in outputs.items():
        API['parse'](raw.decode())
        old = files.read(name)
        require(old is None or old.startswith(HEADER.encode()), 'Refusing foreign output: ' + name)
    return outputs, completed

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--apply', action='store_true')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = Files(ROOT)
    outputs, completed = plan(files)
    pending = {p: raw for p, raw in outputs.items() if files.read(p) != raw}
    if args.apply:
        API['apply'](files, pending)
    else:
        files.verify()
    print(json.dumps({'mio_records': sum(k == 'mio' for k,r in completed), 'advisor_templates': sum(k == 'generated_advisor' for k,r in completed), 'pending_outputs': list(pending), 'applied': args.apply}, indent=2))
    return int(bool(pending) and not args.apply)

if __name__ == '__main__':
    raise SystemExit(main())
