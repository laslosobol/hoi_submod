"""Bind reviewed icon exports without exporting images or changing gameplay.

Usage: --manifest art/verenia/batch-XX.json [--check | --apply]
Default is a read-only plan; --check exits 1 when approved bindings are pending.
Records must carry id, target, kind (focus/spirit), file (repository-relative
definition), source, exports (one native-size TGA), and approved=true. Approval
is never inferred from review/runtime_verified. SHA256 values are read from the
sibling batch-XX-hashes.json written by Build-VereniaArt.py (or --baseline).
The briefs allowlist and inventory's current_icon pin target scope and old value.
Native spirits use the separate native-spirit-briefs.json current_picture pin;
their manifest file must be EaW/common/ideas/zzz_AVI_ideas.txt. On first binding,
the complete native bytes become mod/HoISubmod/common/ideas/zzz_AVI_ideas.txt,
with only approved picture values replaced. Later batches use that override.
Missing approved assets/hashes fail the entire batch; unapproved records skip.
Existing batch sprites cannot be removed or silently changed. Keep previously
approved records in the batch when adding approvals. Tests use memory only.
"""
from __future__ import annotations

import argparse
