def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path)
    parser.add_argument("--baseline", type=Path)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--apply", action="store_true")
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return
    require(args.manifest is not None, "--manifest is required")
    def argument_path(path):
        resolved = path.resolve()
        require(resolved.is_relative_to(ROOT), f"Path outside repository: {path}")
        return resolved.relative_to(ROOT).as_posix()
    files = Files(ROOT)
    outputs, approved, skipped = plan(files, argument_path(args.manifest),
                                     argument_path(args.baseline) if args.baseline else None)
    if args.apply:
        apply(files, outputs)
    for name in sorted(outputs):
        print(name)
    print(f"{approved} approved, {skipped} skipped; {len(outputs)} {'updated' if args.apply else 'pending'} files")
    if args.check and outputs:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
