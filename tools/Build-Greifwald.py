def main():
    stale=[]
    for path, data in out.items():
        p=MOD/path
        if not p.exists() or p.read_bytes()!=data:
            stale.append(path)
            if '--check' not in sys.argv:
                p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
    print(f'{len(out)} generated files; {len(stale)} '+('stale' if '--check' in sys.argv else 'updated'))
    if stale and '--check' in sys.argv: raise SystemExit('\n'.join(stale))

if __name__=='__main__':main()
