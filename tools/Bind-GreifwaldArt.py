"""Bind approved Greifwald art, preserving every gameplay token.

Default: read-only plan. --apply writes bindings; --check fails on pending work.
Manifest: art/greifwald/manifest.json {assets: [{id, kind, targets: [{id,file}],
source, export, gfx, approved, source_sha256, export_sha256}]}.
Native spirit target files may name EaW's zzz_AET_ideas.txt or its same-path mod
override. Only the override is written; its entire baseline must remain identical
except for approved country-idea picture fields. Native focus files are forbidden.

Generator API (no writes; unapproved/missing target returns fallback):
    ART = runpy.run_path(str(ROOT / 'tools/Bind-GreifwaldArt.py'))
    icon = ART['approved_icon'](target_id, fallback)
Returns a full GFX name for focus/dynamic targets and an idea picture key for
spirits. Approved records with missing/corrupt art raise ValueError, never silently
fall back. Optional root and manifest arguments support temporary-fixture tests.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import runpy
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
# The shared parser lives in a test module that parses known CLI options on
# import. Do not let its --help/--eaw parser consume this tool's own arguments.
_argv = sys.argv
try:
    sys.argv = [str(Path(__file__))]
    BASE = runpy.run_path(str(ROOT / 'tools/Bind-VereniaIcons.py'))
finally:
    sys.argv = _argv
Files, apply = BASE['Files'], BASE['apply']
parse, spans, TOKEN = BASE['parse'], BASE['spans'], BASE['TOKEN']
signature, walk, require = BASE['signature'], BASE['walk'], BASE['require']
MOD = 'mod/HoISubmod'
MANIFEST = 'art/greifwald/manifest.json'
NATIVE = 'EaW/common/ideas/zzz_AET_ideas.txt'
OVERRIDE = MOD + '/common/ideas/zzz_AET_ideas.txt'
GFX = MOD + '/interface/HSM_AET_art.gfx'
HEADER = '# Generated by tools/Bind-GreifwaldArt.py; approved Greifwald assets only.\n'
FILES = {
    'focus': {MOD + '/common/national_focus/HSM_AET_campaign.txt',
              MOD + '/common/national_focus/HSM_AET_restored.txt'},
    'spirit': {MOD + '/common/ideas/HSM_AET_campaign.txt', NATIVE, OVERRIDE},
    'dynamic': {MOD + '/common/dynamic_modifiers/HSM_AET_campaign.txt'},
}


def field(raw, kind, target):
    if kind != 'dynamic':
        return BASE['field'](raw, kind, target)
    text = raw.decode('utf-8-sig')
    signature(text)
    matches = [(selector, node) for selector, node in walk(spans(text))
               if len(selector) == 1 and node.key == target]
    require(len(matches) == 1, f'Expected one dynamic modifier: {target}')
    selector, node = matches[0]
    icons = [n for n in node.children if n.key == 'icon']
    require(len(icons) == 1 and icons[0].value and not icons[0].children,
            f'Expected one scalar dynamic icon: {target}')
    return selector + (('icon', 0),), icons[0]


def rewrite(raw, records):
    """Replace selected scalar values only, preserving BOM, comments and CRLF."""
    text = raw.decode('utf-8')
    offset = int(text.startswith('\ufeff'))
    ignored, edits = set(), []
    for kind, target, replacement in records:
        selector, node = field(raw, kind, target)
        require(selector not in ignored, f'Duplicate binding: {target}')
        ignored.add(selector)
        tokens = [m for m in TOKEN.finditer(text, node.start + offset, node.end + offset)
                  if not m[0].isspace() and not m[0].startswith('#')]
        require(len(tokens) == 3 and tokens[1][0] == '=', f'Invalid scalar field: {target}')
        token = tokens[2]
        value = f'"{replacement}"' if token[0].startswith('"') else replacement
        edits.append((token.start(), token.end(), value))
    changed = text
    for start, end, value in sorted(edits, reverse=True):
        changed = changed[:start] + value + changed[end:]
    require(signature(text, ignored) == signature(changed, ignored), 'Gameplay AST changed')
    return changed.encode('utf-8')


def load_manifest(files, manifest=MANIFEST):
    BASE['relative'](manifest, 'art/greifwald')
    raw = files.read(manifest)
    require(raw is not None, f'Missing manifest: {manifest}')
    doc = json.loads(raw.decode('utf-8-sig'))
    require(isinstance(doc, dict) and isinstance(doc.get('assets'), list),
            'Manifest must be an object containing an assets list')
    ids, names, paths, targets = set(), set(), set(), set()
    for row in doc['assets']:
        require(isinstance(row, dict), 'Asset must be an object')
        aid, kind = row.get('id'), row.get('kind')
        require(isinstance(aid, str) and re.fullmatch(r'[A-Za-z0-9_]+', aid), 'Invalid asset id')
        require(isinstance(kind, str) and kind in FILES, f'Invalid asset kind: {kind}')
        require(aid.casefold() not in ids, f'Duplicate asset id: {aid}')
        ids.add(aid.casefold())
        require(type(row.get('approved')) is bool, f'Expected explicit approval boolean: {aid}')
        prefix = 'GFX_HSM_AET_' if kind == 'focus' else 'GFX_idea_HSM_AET_'
        gfx = row.get('gfx', '')
        require(isinstance(gfx, str) and gfx.startswith(prefix)
                and re.fullmatch(r'[A-Za-z0-9_]+', gfx), f'Invalid namespaced sprite: {aid}')
        for name in [gfx] + ([gfx + '_shine'] if kind == 'focus' else []):
            require(name.casefold() not in names, f'Sprite collision: {name}')
            names.add(name.casefold())
        folder = 'goals' if kind == 'focus' else 'ideas'
        expected = {'source': f'art/greifwald/source/{aid}.png',
                    'export': f'{MOD}/gfx/interface/{folder}/HSM_AET_{aid}.tga'}
        for key, path in expected.items():
            require(row.get(key) == path, f'Expected {key} path {path}')
            require(path.casefold() not in paths, f'Duplicate asset path: {path}')
            paths.add(path.casefold())
        require(isinstance(row.get('targets'), list) and row['targets'], f'No targets: {aid}')
        for target in row['targets']:
            require(isinstance(target, dict), f'Invalid target: {aid}')
            tid, file = target.get('id'), target.get('file')
            require(isinstance(tid, str) and re.fullmatch(r'[A-Za-z0-9_]+', tid)
                    and isinstance(file, str) and file in FILES[kind], f'Out-of-scope target: {target}')
            require(tid.startswith('AET_' if file in (NATIVE, OVERRIDE) else 'HSM_AET_'),
                    f'Out-of-scope target id: {tid}')
            require(tid.casefold() not in targets, f'Duplicate target: {tid}')
            targets.add(tid.casefold())
    return doc['assets']


def verified_asset(files, row):
    require(row['approved'] is True, f'Asset not approved: {row["id"]}')
    for key in ('source', 'export'):
        raw = files.read(row[key])
        expected = row.get(key + '_sha256')
        require(raw is not None, f'Missing approved {key}: {row[key]}')
        require(isinstance(expected, str) and re.fullmatch(r'[a-fA-F0-9]{64}', expected)
                and hashlib.sha256(raw).hexdigest() == expected.lower(),
                f'SHA256 mismatch/missing: {row[key]}')
    with Image.open(io.BytesIO(files.read(row['source']))) as source:
        require(source.format == 'PNG' and not getattr(source, 'is_animated', False),
                f'Expected single PNG source: {row["id"]}')
        source.verify()
    size = (99, 86) if row['kind'] == 'focus' else (64, 64)
    raw = files.read(row['export'])
    BASE['native_tga'](raw, size)
    with Image.open(io.BytesIO(raw)) as export:
        export.load()
        require(export.format == 'TGA' and export.mode == 'RGBA' and export.size == size,
                f'Invalid native export: {row["id"]}')
        alpha = export.getchannel('A')
        low, high = alpha.getextrema()
        require(low == 0 and high >= 240 and alpha.getbbox() is not None,
                f'Export needs transparent exterior and visible opaque art: {row["id"]}')
        require(sum(alpha.histogram()[128:]) >= size[0] * size[1] // 100,
                f'Export is effectively empty: {row["id"]}')
    return binding_value(row)


def binding_value(row):
    return row['gfx'].removeprefix('GFX_idea_') if row['kind'] == 'spirit' else row['gfx']


def approved_icon(target_id, fallback, root=ROOT, manifest=MANIFEST):
    """Generator hook: return only hash-verified approved art; never write files."""
    files = Files(Path(root))
    if files.read(manifest) is None:
        return fallback
    rows = load_manifest(files, manifest)
    matches = [row for row in rows if row['approved'] is True
               and any(t['id'] == target_id for t in row['targets'])]
    return verified_asset(files, matches[0]) if matches else fallback


def sprite_block(row):
    """Same two-angle focus shine as Bind-VereniaIcons / native HOI4."""
    name, texture = row['gfx'], Path(row['export']).relative_to(MOD).as_posix()
    base = f'\tspriteType = {{\n\t\tname = {name}\n\t\ttextureFile = "{texture}"\n\t}}\n'
    if row['kind'] != 'focus':
        return base
    shine = f'\tspriteType = {{\n\t\tname = {name}_shine\n\t\ttextureFile = "{texture}"\n\t\teffectFile = "gfx/FX/buttonstate.lua"\n'
    for angle in (-90, 90):
        shine += f'''\t\tanimation = {{
\t\t\tanimationmaskfile = "{texture}"
\t\t\tanimationtexturefile = "gfx/interface/goals/shine_overlay.dds"
\t\t\tanimationrotation = {angle}.0
\t\t\tanimationlooping = no
\t\t\tanimationtime = 0.75
\t\t\tanimationdelay = 0
\t\t\tanimationblendmode = "add"
\t\t\tanimationtype = "scrolling"
\t\t\tanimationrotationoffset = {{ x = 0.0 y = 0.0 }}
\t\t\tanimationtexturescale = {{ x = 1.0 y = 1.0 }}
\t\t}}
'''
    return base + shine + '\t\tlegacy_lazy_load = no\n\t}\n'


def native_integrity(baseline, current, records):
    """Even whitespace/comments must match upstream outside approved pictures."""
    require(baseline is not None, f'Missing EaW baseline: {NATIVE}')
    originals = []
    for kind, tid, replacement in records:
        _, original = field(baseline, kind, tid)
        _, actual = field(current, kind, tid)
        require(actual.value in (original.value, replacement), f'Native picture drift: {tid}')
        originals.append((kind, tid, original.value))
    require(rewrite(current, originals) == baseline, 'Native override differs outside approved pictures')


def plan(files, manifest=MANIFEST):
    rows = load_manifest(files, manifest)
    approved = [r for r in rows if r['approved'] is True]
    edits, inputs = {}, {}
    for row in approved:
        replacement = verified_asset(files, row)
        for target in row['targets']:
            name = OVERRIDE if target['file'] == NATIVE else target['file']
            raw = files.read(name)
            if name == OVERRIDE and raw is None:
                raw = files.read(NATIVE)
            require(raw is not None, f'Missing definition: {name}')
            field(raw, row['kind'], target['id'])
            inputs[name] = raw
            edits.setdefault(name, []).append((row['kind'], target['id'], replacement))
    if OVERRIDE in edits:
        native_integrity(files.read(NATIVE), inputs[OVERRIDE], edits[OVERRIDE])
    generated = (HEADER + 'spriteTypes = {\n' + ''.join(sprite_block(r) for r in
                 sorted(approved, key=lambda row: row['gfx'])) + '}\n').encode('utf-8')
    expected = BASE['sprite_nodes'](generated)
    previous = files.read(GFX)
    if previous is not None:
        require(previous.startswith(HEADER.encode()), f'Unowned interface file: {GFX}')
        require(BASE['sprite_nodes'](previous).keys() <= expected.keys(),
                'Would remove previously bound sprites; keep their approved manifest entries')
    names = {name.casefold() for name in expected}
    for name in files.interfaces:
        if name == GFX:
            continue
        for _, node in walk(parse(files.read(name).decode('utf-8-sig'))):
            if node.key.lower() == 'spritetype':
                require(not any(n.key.lower() == 'name' and n.value.casefold() in names
                                for n in node.children), f'Sprite collision in {name}')
    outputs = {name: rewrite(inputs[name], bindings) for name, bindings in edits.items()}
    if approved or previous is not None:
        outputs[GFX] = generated
    return {name: raw for name, raw in outputs.items() if files.read(name) != raw}, len(approved), len(rows) - len(approved)


def coverage(files, rows):
    """Final-art audit: every added focus and AET national spirit has a target."""
    expected = set()
    for kind, names in FILES.items():
        for name in sorted(names - {OVERRIDE}):
            raw = files.read(name)
            require(raw is not None, f'Missing coverage source: {name}')
            for selector, node in walk(spans(raw.decode('utf-8-sig'))):
                if kind == 'focus' and node.key in ('focus', 'shared_focus', 'joint_focus'):
                    expected.update(n.value for n in node.children if n.key == 'id')
                elif kind == 'spirit' and len(selector) == 3 and tuple(k for k, _ in selector[:2]) == ('ideas', 'country'):
                    expected.add(node.key)
                elif kind == 'dynamic' and len(selector) == 1:
                    expected.add(node.key)
    actual = {target['id'] for row in rows if row['approved'] is True for target in row['targets']}
    require(actual == expected, f'Art coverage mismatch; missing={sorted(expected - actual)}, extra={sorted(actual - expected)}')
    return len(expected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', default=MANIFEST)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--apply', action='store_true')
    modes.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = Files(ROOT)
    outputs, approved, skipped = plan(files, args.manifest)
    if args.apply:
        apply(files, outputs)
    for name in sorted(outputs):
        print(name)
    print(f'{approved} approved, {skipped} skipped; {len(outputs)} {"updated" if args.apply else "pending"} files')
    if args.check and outputs:
        raise SystemExit(1)


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, AssertionError) as error:
        raise SystemExit(str(error))
