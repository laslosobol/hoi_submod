function one(nodes, key) {
    const matches = nodes.filter(n=>n.key===key);
    assert.equal(matches.length, 1, "Expected one direct " + key);
    return matches[0];
}

// Reuse the existing parser for structure; align its nodes to lexical offsets
// so edits preserve every byte outside the selected scalar value.
function document(source) {
    const nodes = parse(source, true), spans = new Map();
    const tokens = [...source.matchAll(/"(?:\\.|[^"\\])*"|#[^\r\n]*|[{}]|[<>=!]+|[^\s{}<>=!#"]+/g)].filter(t=>!t[0].startsWith("#"));
    let cursor = 0;
    function align(body) {
        for (const node of body) {
            if (node.key===null) { cursor++; continue; }
            assert.equal(tokens[cursor++][0], node.key);
            assert.equal(tokens[cursor++][0], node.op);
            const value = tokens[cursor++];
            if (Array.isArray(node.value)) { assert.equal(value[0], "{"); align(node.value); assert.equal(tokens[cursor++][0], "}"); }
            else spans.set(node, {start:value.index, end:value.index+value[0].length});
        }
    }
    align(nodes); assert.equal(cursor, tokens.length);
    return {source, nodes, spans};
}
function definitions(doc, kind) {
    let nodes;
    if (kind==="focuses") nodes=doc.nodes.flatMap(n=>n.key==="focus_tree" ? n.value.filter(x=>x.key==="focus") : [n]).filter(n=>["focus","shared_focus"].includes(n.key)&&Array.isArray(n.value));
    if (kind==="ideas") nodes=doc.nodes.filter(n=>n.key==="ideas").flatMap(n=>n.value.flatMap(category=>Array.isArray(category.value)?category.value:[]));
    if (kind==="modifiers") nodes=doc.nodes;
    return nodes.filter(n=>Array.isArray(n.value)).map(n=>({id:kind==="focuses"?prop(n.value,"id"):n.key, body:n.value})).filter(d=>d.id?.startsWith("HSM_BAR_"));
}
function patchDocument(doc, replacements) {
    let result=doc.source;
    const edits=replacements.map(({node,value})=>{ assert.equal(typeof node.value,"string","Only scalar fields may be patched"); return {...doc.spans.get(node),value}; }).sort((a,b)=>b.start-a.start);
    for (const [i,e] of edits.entries()) { assert(Number.isInteger(e.start)); if(i)assert(e.end<=edits[i-1].start,"Overlapping edits"); result=result.slice(0,e.start)+e.value+result.slice(e.end); }
    parse(result,true);
    return result;
}
function files(root, directory, extension) {
    return fs.readdirSync(path.join(root,directory),{withFileTypes:true}).flatMap(f=>f.isDirectory()?files(root,directory+"/"+f.name,extension):f.name.endsWith(extension)?[directory+"/"+f.name]:[]).sort();
}
const texture = (motif, type) => `gfx/interface/${type}/HSM_BAR_${motif}.tga`;
const sprite = motif => `GFX_HSM_BAR_${motif}`;
const ideaSprite = motif => `GFX_idea_HSM_BAR_${motif}`;
function spriteFiles(art, ideas) {
    const block = body => "# Generated by tools/Build-BarradContentIcons.cjs.\nspriteTypes = {\n"+body.join("\n")+"\n}\n";
    const normal=art.map(m=>` spriteType = { name = "${sprite(m)}" texturefile = "${texture(m,"goals")}" }`);
    const shine=art.map(m=>` spriteType = {
  name = "${sprite(m)}_shine"
  texturefile = "${texture(m,"goals")}"
  effectFile = "gfx/FX/buttonstate.lua"
${[-90,90].map(rotation=>`  animation = {
   animationmaskfile = "${texture(m,"goals")}"
   animationtexturefile = "gfx/interface/goals/shine_overlay.dds"
   animationrotation = ${rotation}.0
   animationlooping = no
   animationtime = 0.75
   animationdelay = 0
   animationblendmode = "add"
   animationtype = "scrolling"
   animationrotationoffset = { x = 0.0 y = 0.0 }
   animationtexturescale = { x = 1.0 y = 1.0 }
  }`).join("\n")}
  legacy_lazy_load = no
 }`);
    return new Map([[registries[0],block(normal)],[registries[1],block(shine)],[registries[2],block(ideas.map(m=>` spriteType = { name = "${ideaSprite(m)}" texturefile = "${texture(m,"ideas")}" }`))]]);
}
function prepare(root) {
    const catalog=JSON.parse(read(root,catalogFile).replace(/^\uFEFF/,"")), mappings={focuses:{},ideas:catalog.ideas,modifiers:catalog.modifiers};
    assert.deepEqual(Object.keys(catalog).sort(),["focuses","ideas","modifiers"]);
    for (const [group,entries] of Object.entries(catalog.focuses)) {
        assert(["common","collegium","civic","mtc_frontiers"].includes(group),"Unknown focus group: "+group);
        for (const [suffix,motif] of Object.entries(entries)) {
            assert(suffix===""?group==="mtc_frontiers":/^\w+$/.test(suffix),"Invalid focus suffix");
            const id="HSM_BAR_"+(group==="common"?suffix:group+(suffix?"_"+suffix:""));
            assert(!Object.hasOwn(mappings.focuses,id),"Duplicate mapped focus: "+id);mappings.focuses[id]=motif;
        }
    }
    assert.equal(Object.keys(mappings.focuses).length,81,"Expected the 81 parent-listed scalar focuses");
    for (const group of Object.values(mappings))for(const [id,motif] of Object.entries(group)) {
        assert(/^HSM_BAR_\w+$/.test(id),"Invalid definition ID: "+id);
        assert(/^(art|dir|cover)_[a-z][a-z0-9_]*$/.test(motif),"Invalid motif: "+motif);
    }
    const motifs=sorted(Object.values(mappings).flatMap(Object.values)),art=motifs.filter(m=>m.startsWith("art_")),ideas=sorted([...Object.values(mappings.ideas),...Object.values(mappings.modifiers)]);
    const docs=new Map(),indexes={},changes=new Map(),errors=[];
    const attempt=(label,fn)=>{try{fn();}catch(e){errors.push(label+": "+message(e));}};
    for(const [kind,dir] of Object.entries({focuses:"national_focus",ideas:"ideas",modifiers:"dynamic_modifiers"})) {
        indexes[kind]=new Map();
        for(const file of files(root,modDir+"common/"+dir,".txt")) {
            const doc=document(read(root,file));docs.set(file,doc);
            for(const def of definitions(doc,kind)) { assert(!indexes[kind].has(def.id),"Duplicate definition: "+def.id);indexes[kind].set(def.id,{...def,file,doc}); }
        }
        for(const [id,motif] of Object.entries(mappings[kind]))attempt(id,()=>{
            const def=indexes[kind].get(id);assert(def,"Mapped definition not found");
            const node=one(def.body,kind==="ideas"?"picture":"icon");assert.equal(typeof node.value,"string","Mapped field must be scalar");
            const value=kind==="focuses"?sprite(motif):kind==="ideas"?"HSM_BAR_"+motif:ideaSprite(motif);
            if(def.file===generatedModifier) { assert.equal(node.value,value,"Generated MTC icon drift: fix its owner generator");return; }
            if(node.value!==value) { if(!changes.has(def.file))changes.set(def.file,[]);changes.get(def.file).push({node,value}); }
        });
    }
    attempt("MTC generator contract",()=>{
        const generated=require(path.join(root,"tools/Build-BarradCollegiumProjects.cjs")).generate()[generatedModifier.slice(modDir.length)];
        assert(generated,"MTC generator output missing");
        assert.equal(prop(one(parse(generated,true),"HSM_BAR_mtk_research").value,"icon"),ideaSprite(mappings.modifiers.HSM_BAR_mtk_research));
    });
    const outputs=spriteFiles(art,ideas);
    for(const [file,edits] of changes)outputs.set(file,patchDocument(docs.get(file),edits));
    const exports=[...art.map(m=>({motif:m,type:"goals",width:99,height:86})),...ideas.map(m=>({motif:m,type:"ideas",width:64,height:64}))].map(job=>({...job,file:modDir+texture(job.motif,job.type)}));
    return {root,catalog,mappings,motifs,art,ideas,docs,indexes,outputs,exports,errors};
}

function powershell(root, body, input) {
    const script="$ErrorActionPreference = 'Stop'\n$data = [Console]::In.ReadToEnd() | ConvertFrom-Json\n"+body;
    const result=spawnSync("pwsh",["-NoProfile","-NonInteractive","-Command",script],{cwd:root,input:JSON.stringify(input),encoding:"utf8",maxBuffer:8*1024*1024});
    assert(!result.error,result.error?.message);assert.equal(result.status,0,(result.stderr||result.stdout||"PowerShell failed").trim());
    return result.stdout.trim();
}
